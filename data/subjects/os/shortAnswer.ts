const GLOSSARY = new Map(OS_GLOSSARY.map((e) => [e.id, e]));
const pagesOf = (slideRef: string) =>
  [...slideRef.matchAll(/p\.(\d+)(?:-(\d+))?/g)].flatMap((m) => {
    const [a, b] = [Number(m[1]), Number(m[2] ?? m[1])];
    return Array.from({ length: b - a + 1 }, (_, i) => a + i);
  });
const label = (e: GlossaryEntry) => [e.ko, e.en && e.en !== e.ko ? e.en : "", e.abbr && e.abbr !== e.ko ? e.abbr : ""].filter(Boolean).join(" · ");
const SUMMARY_MAX = 120;
const summaryOf = (e: GlossaryEntry) => {
  const s = `${e.ko}${e.abbr && e.abbr !== e.ko ? `(${e.abbr})` : ""}: ${e.def}`;
  return s.length <= SUMMARY_MAX ? s : `${s.slice(0, SUMMARY_MAX - 1)}…`;
};

function build(chapter: string, picks: TermPick[]): ShortItem[] {
  return picks.map(([term, wrong, trap, extra], i) => {
    const e = GLOSSARY.get(term);
    if (!e?.def || e.chapter !== chapter) throw new Error(`단답형 용어 ${term}: ${chapter} 용어 사전에 정의가 없음`);
    const handwritten = pagesOf(e.slideRef).some((p) => HANDWRITTEN_PAGES[chapter].includes(p));
    const star = handwritten
      ? { exam: true, examBasis: "handwritten", ...(e.hintIds?.length ? { hintIds: [...e.hintIds] } : {}), summary: summaryOf(e) }
      : e.hintIds?.length
        ? { exam: true, examBasis: "exam-hint", hintIds: [...e.hintIds] }
        : { exam: false };
    const accept = [...new Set([...termAccept(e), ...(extra ?? [])])];
    return {
      term,
      wrong: [wrong],
      q: {
        subject: "os",
        chapter,
        type: "blank",
        id: `os-${chapter}-short-${String(i + 1).padStart(3, "0")}`,
        topic: "용어",
        difficulty: 2,
        slideRef: e.slideRef,
        ...star,
        prompt: "다음 설명에 해당하는 용어를 쓰시오(한국어 또는 영어).",
        text: `${e.def} → {{0}}`,
        blanks: [{ accept }],
        explanation: `${e.def} → ${label(e)}.${e.basis === "교수님 필기" ? " (교수님 필기)" : ""} 헷갈리기 쉬운 답: ${trap}\n근거: ${e.slideRef}`,
      } as Question,
    };
  });
}

export const SHORT_ITEMS: Record<string, ShortItem[]> = Object.fromEntries(Object.entries(PICKS).map(([ch, picks]) => [ch, build(ch, picks)]));

/** 단답형으로 고른 용어 사전 id — terms.ts가 같은 용어로 용어 단답형을 또 만들지 않게 */
export const SHORT_TERM_IDS: ReadonlySet<string> = new Set(Object.values(PICKS).flatMap((ps) => ps.map((p) => p[0])));

export function shortQuestions(chapter: string): Question[] {
  return (SHORT_ITEMS[chapter] ?? []).map((i) => i.q);
}
