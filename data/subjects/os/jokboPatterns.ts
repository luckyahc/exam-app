/** 버디 블록 [크기(K), 할당 여부, 표시(*)] */
export type Blk = readonly [size: number, used: boolean, mark?: boolean];
/** 족보 그림 형식의 버디 메모리 상태: 크기 줄 + |###| 줄. unit 크기 블록 = cell−1칸 */
export function buddyArt(blocks: readonly Blk[], unit: number, cell = 7): string {
  const w = (s: number) => (s / unit) * cell - 1;
  const top = blocks.map(([s, , m]) => ` ${s}K${m ? "*" : ""}`.padEnd(w(s) + 1)).join("").trimEnd();
  const bottom = "|" + blocks.map(([s, u]) => (u ? "#" : " ").repeat(w(s)) + "|").join("");
  return block(top, bottom);
}

