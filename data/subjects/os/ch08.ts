// ── 교체 알고리즘 기준값 (Ch08 p.48 Figure 8.15, p.49-50 Figure 8.16) ──────────
const FIG815_REFS = [2, 3, 2, 1, 5, 2, 4, 5, 3, 2, 5, 2];
const fig815 = (algo: Algo) => simulateReplacement(FIG815_REFS, 3, algo);
/** 프레임 칸 표기: Clock은 use bit 1이면 '*'(슬라이드 표기) */
const frameText = (algo: Algo, s: ReturnType<typeof fig815>["steps"][number], fi: number) => {
  const v = s.frames[fi];
  if (v === null) return "";
  return algo === "clock" && s.use?.[fi] ? `${v}*` : String(v);
};
/** Figure 8.15 진행 표: 프레임 3행 + F 행(+ Clock은 pointer 행). blanks = "행:열"(열은 0부터) */
function fig815Trace(algo: Algo, blanks: readonly string[]) {
  const r = fig815(algo);
  const pick = new Set(blanks);
  const frameOptions = [...new Set(r.steps.flatMap((s) => [0, 1, 2].map((fi) => frameText(algo, s, fi))).filter(Boolean))].sort();
  const rows: { label: string; cells: TraceCell[] }[] = [0, 1, 2].map((fi) => ({
    label: `프레임 ${fi + 1}`,
    cells: r.steps.map((s, c) => {
      const value = frameText(algo, s, fi);
      return pick.has(`${fi}:${c}`) ? { value, blank: true, options: frameOptions } : { value };
    }),
  }));
  rows.push({
    label: "F",
    cells: r.steps.map((s, c) => ({ value: s.fault ? "F" : "-", ...(pick.has(`3:${c}`) ? { blank: true, options: ["F", "-"] } : {}) })),
  });
  if (algo === "clock")
    rows.push({
      label: "pointer(다음 교체 시작 프레임)",
      cells: r.steps.map((s, c) => ({
        value: `프레임 ${(s.pointer ?? 0) + 1}`,
        ...(pick.has(`4:${c}`) ? { blank: true, options: ["프레임 1", "프레임 2", "프레임 3"] } : {}),
      })),
    });
  return { r, columns: FIG815_REFS.map(String), rows };
}
